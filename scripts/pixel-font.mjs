export const fonts = {
  large: { glyphs: large, width: 5, height: 7, advance: 6 },
  small: { glyphs: small, width: 3, height: 5, advance: 4, proportional: true, maxWidth: 5 },
};

for (const [name, font] of Object.entries(fonts)) {
  for (const [char, rows] of Object.entries(font.glyphs)) {
    const width = rows[0]?.length ?? font.width;
    const ok = font.proportional ? width >= font.width && width <= font.maxWidth : width === font.width;
    if (!ok || rows.some((row) => row.length !== width)) throw new Error(`pixel-font: ${name} glyph "${char}" has a bad width`);
  }
}

export const hasGlyph = (char, font = "small") => char in fonts[font].glyphs;

/** Horizontal advance of one glyph, in font pixels. Small glyphs are proportional, large ones monospace. */
const advanceOf = (char, font) => {
  const { glyphs, advance, width, proportional } = fonts[font];
  return proportional ? (glyphs[char]?.[0]?.length ?? width) + advance - width : advance;
};

/** Width in screen pixels of `text` drawn at `scale`. */
export const textWidth = (text, scale = 2, font = "small") => {
  const { advance, width } = fonts[font];
  return [...text].reduce((sum, char) => sum + advanceOf(char, font), 0) * scale - (advance - width) * scale;
};

/** Path data for `text` with its top-left corner at (x, y). Horizontal runs merge into one rectangle each. */
export function textPath(text, x, y, scale = 2, font = "small") {
  const { glyphs } = fonts[font];
  let d = "";
  let left = x;
  for (const char of text) {
    const rows = glyphs[char];
    if (!rows) throw new Error(`pixel-font: no ${font} glyph for "${char}" in "${text}"`);
    rows.forEach((row, rowIndex) => {
      for (const match of row.matchAll(/#+/g)) {
        d += `M${left + match.index * scale} ${y + rowIndex * scale}h${match[0].length * scale}v${scale}h-${match[0].length * scale}z`;
      }
    });
    left += advanceOf(char, font) * scale;
  }
  return d;
}
